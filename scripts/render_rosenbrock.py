"""Write ROSENBROCK.md from data/rosenbrock.jsonl.  python scripts/render_rosenbrock.py"""
import json

import mpmath
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
rows = [json.loads(l) for l in open(ROOT / "data/rosenbrock.jsonl", encoding="utf-8")]


def key(t):
    r = lambda v: [r(x) for x in v] if isinstance(v, list) else f"{v:.10g}"  # noqa: E731
    return json.dumps([r(t["alpha"]), r(t["gamma"]), r(t["b"])])


groups = defaultdict(list)
for t in rows:
    groups[key(t)].append(t)


def display(ts):
    def clean(m):
        m = m.upper().replace("_", "")
        return m[6:] if m.startswith("TSROSW") and m[6:7].isalpha() else m.removeprefix("TS")
    c = Counter(clean(t["method"]) for t in ts)
    return sorted(c, key=lambda n: (-c[n], len(n), n))[0]


libs = sorted({t["library"] for t in rows})
out = ["# Rosenbrock and W-methods\n",
       f"{len(rows)} Rosenbrock tables from {len(libs)} libraries ({', '.join(libs)}), each read at a pinned commit "
       f"and checked with physverify. Tables with the same coefficients (to 10 significant digits) are grouped: "
       f"{len(groups)} groups.\n",
       "A Rosenbrock method replaces the nonlinear solve of an implicit Runge-Kutta method by linear solves with the "
       "Jacobian J. In the standard form (Hairer and Wanner II, Sect. IV.7)\n",
       "```text\n(I - h gamma_ii J) k_i = h f(y0 + sum_j alpha_ij k_j) + h J sum_{j<i} gamma_ij k_j,   y1 = y0 + sum_i b_i k_i\n```\n",
       "Two orders matter:\n",
       "- **Order with the exact Jacobian:** the order when J is the true Jacobian of f.",
       "- **Order as a W-method:** the order when any matrix is used in place of J, as happens with finite-difference, "
       "frozen or Krylov approximations. Most Rodas-type methods drop to order 1 or 2 here; methods designed as W-methods "
       "(ROS34PW, Rodas4PW, RosenbrockW6S4OS) keep a higher order.\n",
       "*R(inf)* is the stability function at infinity. *A-stable* is judged on the imaginary axis: a method is marked "
       "A-stable when |R(iy)| <= 1 for all real y (to 1e-8). A method is L-stable when it is A-stable **and** "
       "R(inf) = 0; R(inf) = 0 alone is not enough (RosenbrockW6S4OS below has R(inf) = 0, but |R(3.52i)| is about "
       "1.006, so it is not A-stable). The coefficients of every table, with its library, the commit read and a link "
       "to the file at that commit, are in `data/rosenbrock.jsonl`; `python scripts/verify_rosenbrock.py` re-checks "
       "them all.\n",
       f"All {len(rows)} recorded orders (exact Jacobian, W-method, embedded) reproduce with physverify, and every "
       f"order claim stored with a table ({sum(1 for t in rows if t['claim'])} of {len(rows)}) is met. For the other "
       "tables the library's claim was read in the census but is not stored here. Not yet here: Rosenbrock tables from "
       "libraries with reported but unconfirmed defects, comparisons with first published sources, the stage times and "
       "the weights of the time derivative of f (these tables are the autonomous form), and dense output.\n",
       "Generated by `scripts/render_rosenbrock.py`; do not edit by hand.\n",
       "| Method | Stages | Order (exact J) | Order as W-method | Embedded order | R(inf) | A-stable | Libraries (name used) |",
       "|---|---|---|---|---|---|---|---|"]
for k, ts in sorted(groups.items(), key=lambda kv: (kv[1][0]["order_exact_jacobian"], kv[1][0]["stages"], display(kv[1]))):
    t = ts[0]
    embs = sorted({x["embedded_order"] for x in ts if x["embedded_order"] is not None})
    where = "; ".join(f"[{x['library']}]({x['source']['url']}) `{x['method']}`" for x in sorted(ts, key=lambda x: x["library"]))
    out.append(f"| {display(ts)} | {t['stages']} | {t['order_exact_jacobian']}{'+' if t['order_exact_jacobian'] == 6 else ''} | "
               f"{t['order_w_method']} | {', '.join(map(str, embs)) or '-'} | {t['r_infinity']:.2g} | "
               f"{'yes' if t['a_stability_margin'] >= -1e-8 else 'no'} | {where} |")
out.append("\nOrder 6+ means the conditions hold through order 6, the highest checked.")

# first published sources (scripts/rosenbrock_sources.py)
import sys  # noqa: E402

sys.path.insert(0, str(ROOT / "scripts"))
from rosenbrock_sources import comparisons  # noqa: E402

out.append("\n## First published sources\n")
out.append("Each card compares the library copies with the method's first published source (a paper, or the author's "
           "own code), transcribed in 50-digit arithmetic in `scripts/rosenbrock_sources.py`, where every coefficient "
           "has its page or line. Each transcription is checked against something else the source prints before it is "
           "used. Library copies are found by their coefficients (equal to 1e-8), whatever the library calls them. "
           "*Difference* is the largest absolute difference over alpha, Gamma and b (and, separately, the embedded "
           "weights).\n")
for src, copies in comparisons():
    dm = max(c["diff"] for c in copies)
    de = [c["embedded_diff"] for c in copies if c["embedded_diff"] is not None]
    out.append(f"### {src['name']}\n")
    out.append(f"- **Reference:** {src['reference']}")
    out.append(f"- **How compared:** {src['how']}")
    out.append(f"- **Check of the transcription:** {src['check_label']}: {src['printed_check']:.1e}.")
    out.append(f"- **Library copies ({len(copies)}):** "
               + "; ".join(f"[{c['library']}]({c['url']}) `{c['method']}` (difference {c['diff']:.1e}"
                           + (f", embedded {c['embedded_diff']:.1e}" if c["embedded_diff"] is not None
                              else "") + ")" for c in copies))
    out.append(f"- **Result:** all {len(copies)} copies agree with the source to {dm:.1e}"
               + (f"; the {len(de)} copies with embedded weights agree to {max(de):.1e}." if de else "."))
    if src.get("time_weights"):
        out.append("- **Stage times and time-derivative weights:** the source gives alpha_i = ("
                   + ", ".join(mpmath.nstr(x, 6) for x in src["times"]) + ") and gamma_i = ("
                   + ", ".join(mpmath.nstr(x, 6) for x in src["time_weights"])
                   + "). They are not stored with the library tables (the autonomous form), so they are not compared "
                   "with the libraries here.\n")
    else:
        out.append("- **Stage times:** alpha_i = (" + ", ".join(mpmath.nstr(x, 6) for x in src["times"])
                   + "). The source uses the autonomous form and gives no time-derivative weights.\n")
    fmt = lambda v: mpmath.nstr(v, 17)  # noqa: E731
    lines = [f"gamma_ii = {fmt(src['gamma'][0][0])}",
             "alpha = [" + "; ".join(", ".join(fmt(x) for x in r) for r in src["alpha"]) + "]",
             "Gamma = [" + "; ".join(", ".join(fmt(x) for x in r) for r in src["gamma"]) + "]",
             "b = [" + ", ".join(fmt(x) for x in src["b"]) + "]"]
    if src.get("embedded") is not None:
        lines.append("b_embedded = [" + ", ".join(fmt(x) for x in src["embedded"]) + "]")
    out.append("Coefficients (standard form, from the source, 17 digits):\n\n```text\n" + "\n".join(lines) + "\n```\n")
(ROOT / "ROSENBROCK.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(f"wrote ROSENBROCK.md: {len(rows)} tables, {len(groups)} groups")
