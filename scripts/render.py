"""Write CATALOGUE.md and SOURCES.md from data/methods.jsonl. Run after any change to the data:

    python scripts/render.py
"""
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
methods = [json.loads(l) for l in open(ROOT / "data/methods.jsonl", encoding="utf-8")]
summary = json.load(open(ROOT / "data/summary.json", encoding="utf-8"))

FAMILY = {
    "ERK": "Explicit Runge-Kutta",
    "DIRK": "Diagonally implicit Runge-Kutta",
    "IRK": "Fully implicit Runge-Kutta",
    "RK": "Runge-Kutta (from libraries that do not say explicit or implicit)",
    "IMEX-ERK": "IMEX pairs: explicit part",
    "IMEX-explicit": "IMEX pairs: explicit part (second layout)",
    "IMEX-DIRK": "IMEX pairs: implicit part",
    "IMEX-implicit": "IMEX pairs: implicit part (second layout)",
}


def name(m):
    n = [x for x in m["names"] if x != m["name"]]
    return m["name"] + (f" (also: {', '.join(n[:3])}{', ...' if len(n) > 3 else ''})" if n else "")


def libs(m):
    ls = m["libraries"]
    return ", ".join(ls[:4]) + (f" and {len(ls) - 4} more" if len(ls) > 4 else "")


def esc(s):
    return str(s).replace("|", "\\|")


out = ["# Catalogue of Runge-Kutta tables\n",
       f"{summary['methods_published']} methods: the {summary['tables_published']} published tables grouped by their "
       "coefficients (equal to 12 significant digits). *Order* is the order the coefficients satisfy, computed from the "
       "order conditions to 50 digits; *stage order* is the order of the internal stages. A method marked "
       "*source* was compared with its first published source ([SOURCES.md](SOURCES.md)). The coefficients of each "
       "method are in `data/methods.jsonl`; each library copy, with file and line, is in `data/tables.jsonl`.\n",
       "Generated by `scripts/render.py`; do not edit by hand.\n"]
byfam = defaultdict(list)
for m in methods:
    byfam[m["family"]].append(m)
for fam in FAMILY:
    ms = sorted(byfam.get(fam, []), key=lambda m: (m["order"] or 0, m["stages"], m["name"].lower()))
    if not ms:
        continue
    out.append(f"\n## {FAMILY[fam]} ({len(ms)})\n")
    out.append("| Method | Stages | Order | Stage order | Checked | Libraries |")
    out.append("|---|---|---|---|---|---|")
    for m in ms:
        checked = ", ".join(x for x in ["source" if m["first_source"] else "", "NodePy" if m["nodepy_agrees"] else ""] if x)
        out.append(f"| {esc(name(m))} | {m['stages']} | {m['order']} | {m['stage_order']} | {checked} | {esc(libs(m))} |")
(ROOT / "CATALOGUE.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")

src = ["# First published sources\n",
       "Each row is one method and its reference: a paper or report, the author's own coefficient file, or a "
       "construction from the definition in a standard text. *Largest difference* is the largest absolute difference "
       "between any library copy and the reference, over A, b, c and the embedded weights; differences near 1e-15 "
       "come from printed decimals. A copy that differs from its reference is in [ERRATA.md](ERRATA.md), not here.\n",
       "Generated by `scripts/render.py`; do not edit by hand.\n",
       "| Method | Order | Reference | Largest difference | Library copies |", "|---|---|---|---|---|"]
byref = {}
for m in methods:
    for x in m["first_source"] or []:
        e = byref.setdefault((m["name"], x["citation"] or x["reference"]),
                             {"order": m["order"], "d": 0.0, "libs": set(), "n": 0})
        e["d"] = max(e["d"], x["largest_difference"] or 0.0)
        e["libs"].update(m["libraries"])
        e["n"] += m["copies"]
for (nm, ref), e in sorted(byref.items(), key=lambda kv: (kv[1]["order"] or 0, kv[0][0].lower())):
    ls = sorted(e["libs"])
    lib = ", ".join(ls[:5]) + (f" and {len(ls) - 5} more" if len(ls) > 5 else "")
    src.append(f"| {esc(nm)} | {e['order']} | {esc(ref)} | {e['d']:.1e} | {e['n']} in {esc(lib)} |")
(ROOT / "SOURCES.md").write_text("\n".join(src) + "\n", encoding="utf-8", newline="\n")
print("wrote CATALOGUE.md and SOURCES.md")
